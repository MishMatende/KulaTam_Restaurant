#!/usr/bin/env python3
"""Generate the Supabase migration for the KulaTam menu from src/data/menu.json.

Usage: python3 scripts/generate_migration.py
Writes supabase/migrations/20261010000000_kulatam_menu_kt.sql
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "data" / "menu.json"
OUTPUT = ROOT / "supabase" / "migrations" / "20261010000000_kulatam_menu_kt.sql"

SCHEMA = """\
-- =====================================================================
-- KulaTam Restaurant (Owang Energy, Kitengela) - menu schema + seed data
--
-- Every object created here ends in _kt so it cannot clash with the
-- other branch's tables in this shared Supabase project. The only thing
-- shared between branches is auth.users.
--
-- Safe to re-run: tables/policies are created idempotently and the seed
-- data is upserted by slug (re-running resets seeded rows to these values).
--
-- GENERATED by scripts/generate_migration.py from src/data/menu.json.
-- Edit the JSON and regenerate rather than editing this file by hand.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------

-- Users (from the shared auth.users) allowed to manage this branch's menu.
create table if not exists public.admins_kt (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.categories_kt (
  id          uuid primary key default gen_random_uuid(),
  slug        text not null unique,
  name        text not null,
  description text,
  icon        text not null default 'ti-tools-kitchen-2',  -- Tabler icon class
  tone        text not null default 'am'
              check (tone in ('am', 'lu', 'me', 'dr', 'sn', 'pu', 'tl')),
  sort_order  integer not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.subcategories_kt (
  id          uuid primary key default gen_random_uuid(),
  category_id uuid not null references public.categories_kt (id) on delete cascade,
  slug        text not null unique,
  name        text not null,
  sort_order  integer not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.menu_items_kt (
  id                uuid primary key default gen_random_uuid(),
  subcategory_id    uuid not null references public.subcategories_kt (id) on delete restrict,
  slug              text not null unique,
  name              text not null,
  description       text,
  price             integer not null check (price >= 0),  -- KSh
  is_vegetarian     boolean not null default false,
  is_featured       boolean not null default false,
  badge             text,
  image_url         text,
  is_available      boolean not null default true,
  sort_order        integer not null default 0,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- Upgrade a table created by an earlier version of this script: drop the
-- delivery-app price columns and rename store_price -> price.
alter table public.menu_items_kt drop column if exists app_price;
alter table public.menu_items_kt drop column if exists app_price_rounded;
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'menu_items_kt' and column_name = 'store_price'
  ) then
    alter table public.menu_items_kt rename column store_price to price;
  end if;
end;
$$;

create index if not exists subcategories_kt_category_id_idx on public.subcategories_kt (category_id);
create index if not exists menu_items_kt_subcategory_id_idx on public.menu_items_kt (subcategory_id);
create index if not exists menu_items_kt_featured_idx on public.menu_items_kt (is_featured) where is_featured;

-- ---------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------

create or replace function public.set_updated_at_kt()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_updated_at_kt on public.categories_kt;
create trigger set_updated_at_kt before update on public.categories_kt
  for each row execute function public.set_updated_at_kt();

drop trigger if exists set_updated_at_kt on public.subcategories_kt;
create trigger set_updated_at_kt before update on public.subcategories_kt
  for each row execute function public.set_updated_at_kt();

drop trigger if exists set_updated_at_kt on public.menu_items_kt;
create trigger set_updated_at_kt before update on public.menu_items_kt
  for each row execute function public.set_updated_at_kt();

-- ---------------------------------------------------------------------
-- Row Level Security
-- Anyone can read the active menu. Only users listed in admins_kt can
-- change it, so a user signed in for the other branch cannot.
-- ---------------------------------------------------------------------

create or replace function public.is_admin_kt()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins_kt where user_id = auth.uid());
$$;

revoke all on function public.is_admin_kt() from public;
grant execute on function public.is_admin_kt() to anon, authenticated;

alter table public.admins_kt        enable row level security;
alter table public.categories_kt    enable row level security;
alter table public.subcategories_kt enable row level security;
alter table public.menu_items_kt    enable row level security;

grant select on public.categories_kt, public.subcategories_kt, public.menu_items_kt to anon, authenticated;
grant insert, update, delete on public.categories_kt, public.subcategories_kt, public.menu_items_kt to authenticated;
grant select on public.admins_kt to authenticated;

drop policy if exists "admins_kt: read own row" on public.admins_kt;
create policy "admins_kt: read own row" on public.admins_kt
  for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "categories_kt: public read" on public.categories_kt;
create policy "categories_kt: public read" on public.categories_kt
  for select to anon, authenticated
  using (is_active or (select public.is_admin_kt()));

drop policy if exists "categories_kt: admin write" on public.categories_kt;
create policy "categories_kt: admin write" on public.categories_kt
  for all to authenticated
  using ((select public.is_admin_kt()))
  with check ((select public.is_admin_kt()));

drop policy if exists "subcategories_kt: public read" on public.subcategories_kt;
create policy "subcategories_kt: public read" on public.subcategories_kt
  for select to anon, authenticated
  using (is_active or (select public.is_admin_kt()));

drop policy if exists "subcategories_kt: admin write" on public.subcategories_kt;
create policy "subcategories_kt: admin write" on public.subcategories_kt
  for all to authenticated
  using ((select public.is_admin_kt()))
  with check ((select public.is_admin_kt()));

drop policy if exists "menu_items_kt: public read" on public.menu_items_kt;
create policy "menu_items_kt: public read" on public.menu_items_kt
  for select to anon, authenticated
  using (true);

drop policy if exists "menu_items_kt: admin write" on public.menu_items_kt;
create policy "menu_items_kt: admin write" on public.menu_items_kt
  for all to authenticated
  using ((select public.is_admin_kt()))
  with check ((select public.is_admin_kt()));
"""

FOOTER = """
commit;

-- ---------------------------------------------------------------------
-- To let a user manage this branch's menu, run (with their auth email):
--
--   insert into public.admins_kt (user_id)
--   select id from auth.users where email = 'someone@example.com'
--   on conflict do nothing;
-- ---------------------------------------------------------------------
"""


def lit(value):
    """Render a Python value as a SQL literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def values_block(rows):
    return ",\n".join("  (" + ", ".join(lit(v) for v in row) + ")" for row in rows)


def build(menu):
    categories, subcategories, items = [], [], []
    for c_order, cat in enumerate(menu["categories"], start=1):
        categories.append((cat["slug"], cat["name"], cat["description"], cat["icon"], cat["tone"], c_order))
        for s_order, sub in enumerate(cat["subcategories"], start=1):
            subcategories.append((cat["slug"], sub["slug"], sub["name"], s_order))
            for i_order, item in enumerate(sub["items"], start=1):
                items.append((
                    sub["slug"], item["slug"], item["name"], item.get("description"), item["price"],
                    item.get("veg", False), item.get("featured", False), item.get("badge"), i_order,
                ))

    return f"""{SCHEMA}
-- ---------------------------------------------------------------------
-- Seed data: {len(categories)} categories, {len(subcategories)} subcategories, {len(items)} menu items
-- ---------------------------------------------------------------------

insert into public.categories_kt (slug, name, description, icon, tone, sort_order)
values
{values_block(categories)}
on conflict (slug) do update set
  name        = excluded.name,
  description = excluded.description,
  icon        = excluded.icon,
  tone        = excluded.tone,
  sort_order  = excluded.sort_order;

insert into public.subcategories_kt (category_id, slug, name, sort_order)
select c.id, v.slug, v.name, v.sort_order
from (values
{values_block(subcategories)}
) as v (category_slug, slug, name, sort_order)
join public.categories_kt c on c.slug = v.category_slug
on conflict (slug) do update set
  category_id = excluded.category_id,
  name        = excluded.name,
  sort_order  = excluded.sort_order;

insert into public.menu_items_kt
  (subcategory_id, slug, name, description, price, is_vegetarian, is_featured, badge, sort_order)
select s.id, v.slug, v.name, v.description, v.price, v.is_vegetarian, v.is_featured, v.badge, v.sort_order
from (values
{values_block(items)}
) as v (subcategory_slug, slug, name, description, price, is_vegetarian, is_featured, badge, sort_order)
join public.subcategories_kt s on s.slug = v.subcategory_slug
on conflict (slug) do update set
  subcategory_id = excluded.subcategory_id,
  name           = excluded.name,
  description    = excluded.description,
  price          = excluded.price,
  is_vegetarian  = excluded.is_vegetarian,
  is_featured    = excluded.is_featured,
  badge          = excluded.badge,
  sort_order     = excluded.sort_order;
{FOOTER}"""


def main():
    menu = json.loads(SOURCE.read_text(encoding="utf-8"))
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(build(menu), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
